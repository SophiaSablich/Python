print('\nUsando operadores Aritméticos')

n1 = int(input('\nQual o primeiro número? '))
n2 = int(input('\nQual o segundo número? '))

soma = n1 + n2
sub = n1 - n2
mult = n1 * n2
div = n1 / n2
quoc = n1 // n2
rest = n1 % n2
pot = n1 ** n2

print('\nA soma é {}'.format(soma)) 
print('\nA subtração é {}'.format(sub))
print('\nA multiplicação é {}'.format(mult))
print('\nA divisão é {}'.format(div))
print('\nO quociente da divisão é {}'.format(quoc))
print('\nO resto da divisão é {}'.format(rest))
print('\nA potenciação é {}'.format(pot))